#!/bin/sh
# Regenerates THIRD_PARTY_NOTICES at the repository root (spec A11.7, JA30).
#
#   sh scripts/notices.sh
#
# Every module in go.mod's require directives (direct and indirect) gets a
# "== <module> <version> ==" header followed by the full text of each license
# file at the top of its module directory (LICENSE*, LICENCE*, COPYING*,
# NOTICE*, PATENTS*). The Go standard library, which is linked into every
# binary, comes first. cmd/masil/notices_test.go fails when a go.mod module
# has no header, so run this after every dependency change.
#
# Exit codes: 0 ok, 1 a module has no license file or could not be downloaded.

set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/THIRD_PARTY_NOTICES"
tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT

cd "$root"

# license_files DIR prints the license-like files at the top of DIR, sorted.
license_files() {
	for f in "$1"/*; do
		[ -f "$f" ] || continue
		case "$(basename "$f" | tr '[:upper:]' '[:lower:]')" in
		licen[cs]e* | copying* | notice* | patents*) printf '%s\n' "$f" ;;
		esac
	done | LC_ALL=C sort
}

# emit HEADER DIR appends one notice section.
emit() {
	files=$(license_files "$2")
	if [ -z "$files" ]; then
		echo "notices: no license file in $2 ($1)" >&2
		exit 1
	fi
	printf '== %s ==\n' "$1" >>"$tmp"
	printf '%s\n' "$files" | while IFS= read -r f; do
		printf '\n-- %s --\n\n' "$(basename "$f")" >>"$tmp"
		# Normalise CRLF so the file is byte-identical on every OS.
		tr -d '\r' <"$f" >>"$tmp"
		# Make sure each license ends with a newline.
		[ -z "$(tail -c 1 "$f")" ] || printf '\n' >>"$tmp"
	done
	printf '\n' >>"$tmp"
}

{
	echo "Third-party notices for masil"
	echo
	echo "masil binaries include code from the Go standard library and from the"
	echo "Go modules below. Their copyright and license notices follow."
	echo "Generated by scripts/notices.sh from go.mod — do not edit by hand."
	echo
} >"$tmp"

emit "Go standard library" "$(go env GOROOT)"

# Module path and version from every require line, sorted by path.
mods=$(awk '
	/^require \(/ { inblock = 1; next }
	inblock && /^\)/ { inblock = 0; next }
	inblock && NF >= 2 { print $1, $2; next }
	/^require [^(]/ { print $2, $3 }
' go.mod | LC_ALL=C sort)

# A here-document (not a pipe) keeps the loop in this shell so `exit 1` stops
# the script before the old file is replaced.
while read -r path version; do
	[ -n "$path" ] || continue
	dir=$(go mod download -json "$path@$version" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",*$/\1/p')
	if [ -z "$dir" ] || [ ! -d "$dir" ]; then
		echo "notices: cannot locate $path@$version in the module cache" >&2
		exit 1
	fi
	emit "$path $version" "$dir"
done <<EOF
$mods
EOF

mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
