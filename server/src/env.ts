// App-wide environment types (server-architecture.md 4.1).
import type { Context } from "hono";

export type Env = Cloudflare.Env; // generated by `wrangler types` from wrangler.jsonc

export interface AuthContext {
  userId: string;
  sessionId: string;
  handle: string;
  role: "user" | "admin";
}

export type AppEnv = {
  Bindings: Env;
  Variables: { auth: AuthContext; requestId: string };
};

export type AppContext = Context<AppEnv>;

/** What helpers need to run outside a request too (DO, cron). */
export interface Runtime {
  env: Env;
  waitUntil(p: Promise<unknown>): void;
}

export function rt(c: AppContext): Runtime {
  return { env: c.env, waitUntil: (p) => c.executionCtx.waitUntil(p) };
}
