package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"strconv"
	"strings"
)

const genHeader = "// Code generated by \"go generate ./internal/i18n\"; DO NOT EDIT.\n// Source: internal/i18n/locales/*/%s.toml\n\npackage i18n\n\n"

// goName turns snake_case into CamelCase: members_count => MembersCount.
func goName(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// argName turns a param into a Go parameter name that cannot collide with a
// keyword, a predeclared type the method uses, or the strconv import.
func argName(p string) string {
	n := goName(p)
	n = strings.ToLower(n[:1]) + n[1:]
	if token.IsKeyword(n) || slices.Contains([]string{"string", "int", "strconv", "any", "true", "false", "nil"}, n) {
		n += "Arg"
	}
	return n
}

// emit returns every generated Go file by name.
func emit(c *Catalog) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, a := range c.Areas {
		src, err := emitArea(a)
		if err != nil {
			return nil, err
		}
		out["zz_"+a.Name+"_gen.go"] = src
	}
	src, err := emitCatalog(c)
	if err != nil {
		return nil, err
	}
	out["zz_catalog_gen.go"] = src
	return out, nil
}

func emitCatalog(c *Catalog) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by \"go generate ./internal/i18n\"; DO NOT EDIT.\n// Source: internal/i18n/locales/ko/*.toml (one field per area file)\n\npackage i18n\n\n")
	b.WriteString("// T is one language's message catalog, one field per area. Get it from For\n// or KoT (or ctx.T in screens); never build it by hand.\ntype T struct {\n\tlocale Locale\n\n")
	for _, a := range c.Areas {
		fmt.Fprintf(&b, "\t%s %s\n", a.Field, a.Type)
	}
	b.WriteString("}\n\nfunc newT(l Locale) *T {\n\tt := &T{locale: l}\n")
	for _, a := range c.Areas {
		fmt.Fprintf(&b, "\tt.%s = %s{t}\n", a.Field, a.Type)
	}
	b.WriteString("\treturn t\n}\n\n// areas indexes every area table by file name (dynamic Lookup, Entries).\nvar areas = map[string]*area{\n")
	for _, a := range c.Areas {
		fmt.Fprintf(&b, "\t%q: &area%s,\n", a.Name, a.Field)
	}
	b.WriteString("}\n")
	return gofmt("zz_catalog_gen.go", b.Bytes())
}

func emitArea(a *Area) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, genHeader, a.Name)
	needStrconv := false
	for _, k := range a.Keys {
		for _, p := range k.Params {
			if p.Type == "int" {
				needStrconv = true
			}
		}
	}
	if needStrconv {
		b.WriteString("import \"strconv\"\n\n")
	}
	fmt.Fprintf(&b, "// %s holds the %q area messages (locales/*/%s.toml).\ntype %s struct{ t *T }\n\n", a.Type, a.Name, a.Name, a.Type)
	fmt.Fprintf(&b, "var area%s = area{\n\tname: %q,\n\tkeys: map[string]*entry{\n", a.Field, a.Name)
	for _, k := range a.Keys {
		fmt.Fprintf(&b, "\t\t%q: {\n", k.Name)
		emitMeta(&b, k)
		b.WriteString("\t\t\ttext: map[Locale]Forms{\n")
		for _, lang := range langs {
			r := k.Text[lang]
			if r == nil {
				continue
			}
			fmt.Fprintf(&b, "\t\t\t\t%s: {", goLocale[lang])
			var fs []string
			if r.One != "" {
				fs = append(fs, "One: "+strconv.Quote(r.One))
			}
			fs = append(fs, "Other: "+strconv.Quote(r.Other))
			if r.Short != "" {
				fs = append(fs, "Short: "+strconv.Quote(r.Short))
			}
			b.WriteString(strings.Join(fs, ", "))
			b.WriteString("},\n")
		}
		b.WriteString("\t\t\t},\n\t\t},\n")
	}
	b.WriteString("\t},\n}\n")
	for _, k := range a.Keys {
		emitMethod(&b, a, k, false)
		if k.Short != "" {
			emitMethod(&b, a, k, true)
		}
	}
	return gofmt("zz_"+a.Name+"_gen.go", b.Bytes())
}

// emitMeta writes the entry fields the runtime needs besides the text.
func emitMeta(b *bytes.Buffer, k *Key) {
	if len(k.Params) > 0 {
		var ps []string
		for _, p := range k.Params {
			ps = append(ps, strconv.Quote(p.Name))
		}
		fmt.Fprintf(b, "\t\t\tparams: []string{%s},\n", strings.Join(ps, ", "))
	}
	if k.Count != "" {
		fmt.Fprintf(b, "\t\t\tcount: %q,\n", k.Count)
	}
}

func emitMethod(b *bytes.Buffer, a *Area, k *Key, short bool) {
	name := goName(k.Name)
	if short {
		name += "Short"
	}
	var sig, args []string
	countArg := "0"
	for _, p := range k.Params {
		n := argName(p.Name)
		sig = append(sig, n+" "+p.Type)
		v := n
		if p.Type == "int" {
			v = "strconv.Itoa(" + n + ")"
		}
		args = append(args, strconv.Quote(p.Name), v)
		if p.Name == k.Count {
			countArg = n
		}
	}
	desc := strings.Join(strings.Fields(k.Desc), " ")
	if short {
		desc += " (short form)"
	}
	fmt.Fprintf(b, "\n// %s: %s\nfunc (a_ %s) %s(%s) string {\n", name, desc, a.Type, name, strings.Join(sig, ", "))
	call := []string{"&area" + a.Field, strconv.Quote(k.Name), strconv.FormatBool(short), countArg}
	call = append(call, args...)
	fmt.Fprintf(b, "\treturn a_.t.render(%s)\n}\n", strings.Join(call, ", "))
}

func gofmt(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gofmt %s: %v\n%s", name, err, src)
	}
	return out, nil
}

// formatTOML rewrites one source file: header comments kept, keys sorted,
// fields in a fixed order.
func formatTOML(f *File) []byte {
	var b strings.Builder
	b.WriteString(f.Header)
	for i, key := range sortedKeys(f.Entries) {
		if i > 0 || f.Header != "" {
			b.WriteString("\n")
		}
		r := f.Entries[key]
		fmt.Fprintf(&b, "[%s]\n", key)
		line := func(field, v string) { fmt.Fprintf(&b, "%s = %s\n", field, v) }
		if r.has["desc"] {
			line("desc", tomlString(r.Desc))
		}
		if len(r.Params) > 0 {
			var ps []string
			for _, p := range r.Params {
				ps = append(ps, p.Name+" = "+tomlString(p.Type))
			}
			line("params", "{ "+strings.Join(ps, ", ")+" }")
		}
		if r.has["count"] {
			line("count", tomlString(r.Count))
		}
		if r.has["max"] {
			line("max", strconv.Itoa(r.Max))
		}
		if r.has["no_truncate"] {
			line("no_truncate", strconv.FormatBool(r.NoTruncate))
		}
		if r.has["legal"] {
			line("legal", strconv.FormatBool(r.Legal))
		}
		for _, fv := range [][2]string{{"one", r.One}, {"other", r.Other}, {"short", r.Short}} {
			if r.has[fv[0]] {
				line(fv[0], tomlString(fv[1]))
			}
		}
	}
	return []byte(b.String())
}

// tomlString writes a TOML basic string.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
