package imgrender_test

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"testing"
)

// Pending item 12, client and server kept consistent: the server refuses a
// WebP/GIF that still carries metadata (server/src/lib/uploads.ts
// imageMetadataCheck, api.md 5.14). This test writes what PrepareUpload makes
// of hostile files to a fixture the server's vitest suite reads
// (server/test/unit/uploads-metadata.test.ts): every input must be refused
// there as "metadata" and every output accepted as "ok". The fixture must
// match what the client produces now; regenerate it with
//
//	MASIL_UPDATE_SERVER_FIXTURE=1 go test ./internal/imgrender -run TestStrippedUploadsServerFixture
const serverFixture = "../../server/test/fixtures/client-stripped-uploads.ts"

func TestStrippedUploadsServerFixture(t *testing.T) {
	type upload struct {
		name, ext string
		in        []byte
	}
	var cases []upload

	cases = append(cases, upload{"webp still: ICCP, EXIF, XMP around ALPH+VP8", "webp", readFixture(t, "still-alpha-meta.webp")})

	src := parseRIFF(t, readFixture(t, "anim-meta.webp")) // VP8X ICCP ANIM ANMF ANMF EXIF XMP
	exif := buildWebP(riffChunk{"EXIF", []byte("Exif\x00\x00GPS 37.5665 iPhone")})[12:]
	xmp := buildWebP(riffChunk{"XMP ", []byte("<x:xmpmeta>GPS</x:xmpmeta>")})[12:]
	f1 := append(append([]byte{}, src[3].data...), exif...)
	f2 := append(append([]byte{}, src[4].data...), xmp...)
	cases = append(cases, upload{"webp animated: EXIF and XMP inside the frames too", "webp",
		buildWebP(src[0], src[1], src[2], riffChunk{"ANMF", f1}, riffChunk{"ANMF", f2}, src[5], src[6])})
	cases = append(cases, upload{"webp animated: EXIF and XMP only inside the frames", "webp",
		buildWebP(src[0], src[2], riffChunk{"ANMF", f1}, riffChunk{"ANMF", f2})})

	lossless := parseRIFF(t, readFixture(t, "simple-lossless.webp"))[0]
	cases = append(cases, upload{"webp simple: trailing EXIF, XMP, ICCP, unknown", "webp", buildWebP(lossless,
		riffChunk{"EXIF", []byte("Exif\x00\x00MM GPS 37.5665")}, riffChunk{"XMP ", []byte("<x:xmpmeta/>")},
		riffChunk{"ICCP", []byte("ICCPROFILE")}, riffChunk{"ZZZZ", []byte("SECRET")})})

	clean := twoFrameGIF(t)
	h := gifHeaderLen(clean)
	gce := bytes.Index(clean, []byte{0x21, 0xF9, 0x04})
	netscape := ext(0xFF, subBlocks("NETSCAPE2.0", "\x01\x00\x00", "SECRET"))
	for _, c := range []struct {
		name string
		in   []byte
	}{
		{"gif: comment", insertAt(clean, h, gifComment)},
		{"gif: XMP application extension", insertAt(clean, h, gifXMP)},
		{"gif: ICC application extension", insertAt(clean, h, gifICC)},
		{"gif: unknown extension", insertAt(clean, len(clean)-1, gifUnknown)},
		{"gif: plain text", insertAt(clean, h, gifGCEAlone, gifPlain)},
		{"gif: NETSCAPE2.0 with a sub-block after its loop count", insertAt(clean, h, netscape)},
		{"gif: GCE with a sub-block after its 4 bytes", insertAt(clean, gce+3+4, []byte("\x06SECRET"))},
		{"gif: all of the above at once", insertAt(insertAt(insertAt(clean, len(clean)-1, gifComment, gifUnknown),
			gce+3+4, []byte("\x06SECRET")), h, gifXMP, gifICC, gifComment, gifGCEAlone, gifPlain, netscape)},
	} {
		cases = append(cases, upload{c.name, "gif", c.in})
	}

	var b bytes.Buffer
	b.WriteString("// Generated by internal/imgrender/servercheck_test.go (TestStrippedUploadsServerFixture). Do not edit.\n")
	b.WriteString("// Hostile WebP/GIF uploads (in) and what the client's PrepareUpload sends for them (out), base64.\n")
	b.WriteString("export const clientStrippedUploads: { name: string; ext: \"webp\" | \"gif\"; in: string; out: string }[] = [\n")
	for _, c := range cases {
		out, _ := prepare(t, "x."+c.ext, c.in)
		assertNoLeaks(t, out)
		fmt.Fprintf(&b, "  {\n    name: %q,\n    ext: %q,\n    in: %q,\n    out: %q,\n  },\n",
			c.name, c.ext, base64.StdEncoding.EncodeToString(c.in), base64.StdEncoding.EncodeToString(out))
	}
	b.WriteString("];\n")

	path := filepath.FromSlash(serverFixture)
	if os.Getenv("MASIL_UPDATE_SERVER_FIXTURE") != "" {
		if err := os.WriteFile(path, b.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with MASIL_UPDATE_SERVER_FIXTURE=1)", path, err)
	}
	if !bytes.Equal(got, b.Bytes()) {
		t.Fatalf("%s is not what PrepareUpload produces now; regenerate with MASIL_UPDATE_SERVER_FIXTURE=1 and rerun the server's vitest", path)
	}
}
